// Trusted post-build stage. The build container must already be destroyed.
const fs = require('fs/promises');
const path = require('path');
const {execFile} = require('child_process');
const {promisify} = require('util');
const run = promisify(execFile);

async function finalize(rawDir, scriptsDir, authorizeSigning, config=process.env) {
  const sealed = await fs.mkdtemp(path.join(path.dirname(rawDir), 'sealed-'));
  await fs.chmod(sealed, 0o700);
  const env = {PATH:config.PATH, JAVA_HOME:config.JAVA_HOME, LANG:'C', LC_ALL:'C',
    APKSIGNER_PATH:config.APKSIGNER_PATH || 'apksigner', BUNDLETOOL_JAR:config.BUNDLETOOL_JAR};
  try {
    // Filenames are hints only. Never trust a manifest generated by imported code.
    const candidates = (await fs.readdir(rawDir)).filter(f=>/^[A-Za-z0-9][A-Za-z0-9._-]{0,150}\.(apk|aab)$/.test(f));
    if(!candidates.some(f=>f.endsWith('.apk')) || !candidates.some(f=>f.endsWith('.aab'))) throw Error('Both outputs required');
    const files=[];
    const root=await fs.realpath(rawDir);
    for(const name of candidates) {
      const source=path.join(rawDir,name), stat=await fs.lstat(source);
      if(!stat.isFile() || stat.isSymbolicLink() || stat.size===0 || stat.size>200*1024*1024 || !((await fs.realpath(source)).startsWith(root+path.sep))) throw Error('Invalid output file');
      const file=path.join(sealed,name);await fs.copyFile(source,file);await fs.chmod(file,0o600);
      if(authorizeSigning && name.endsWith('.aab')) {
        // Explicit per-build owner consent; no credentials enter the source sandbox.
        await run('bash',['-c','source "$1"; sign_aab "$2"','sign',path.join(scriptsDir,'sign_artifacts.sh'),file], {
          timeout:90_000,maxBuffer:1024*1024,env:{...env,SIGNING_AUTHORIZED:'true',KEYSTORE_PATH:config.KEYSTORE_PATH,
            KEYSTORE_ALIAS:config.KEYSTORE_ALIAS,KEYSTORE_PASS:config.KEYSTORE_PASS,KEY_PASS:config.KEY_PASS},
        });
      }
      files.push(file);
    }
    const {stdout}=await run('python3',[path.join(scriptsDir,'verify_artifacts.py'),...files],{env,timeout:180_000,maxBuffer:1024*1024});
    const verified=JSON.parse(stdout);
    await fs.writeFile(path.join(sealed,'verified.json'),JSON.stringify(verified),{mode:0o600});
    return {directory:sealed,verified};
  } catch {
    await fs.rm(sealed,{recursive:true,force:true});
    // Child-process errors can include credentials in source-controlled output.
    throw Error('Trusted signing/signature validation failed; artifacts withheld');
  }
}
module.exports={finalize};
